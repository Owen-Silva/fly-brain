def check_labels():
    """FlyWire's own annotations for every ID above (pandas DataFrame)."""
    from pathlib import Path

    import pandas as pd
    root = Path(__file__).resolve().parents[2]
    lab = pd.read_parquet(root / "data" / "cache" / "connectome_630_neurons.parquet",
                          columns=["root_id", "super_class", "cell_class", "cell_sub_class",
                                   "cell_type", "hemibrain_type", "side", "top_nt", "known_nt",
                                   "sign", "ref_sign"])
    rows = []
    for name, ids in [("JON_CE", JON_CE), ("JON_F", JON_F), ("JON_DM", JON_DM),
                      ("aBN1", [ABN1]), ("aDN1", [ADN1]), ("aDN2", [ADN2]),
                      ("three_inhibitory", THREE_INHIBITORY)]:
        for i in ids:
            rows.append({"set": name, "root_id": int(i)})
    df = pd.DataFrame(rows).merge(lab, on="root_id", how="left")
    return df
